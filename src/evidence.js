export function getThemes(themeIds = []) {
  return themeIds.map((themeId) => EVIDENCE_THEMES[themeId]).filter(Boolean);
}

export function getSourcesForThemes(themeIds = []) {
  const sourceIds = new Set();
  getThemes(themeIds).forEach((theme) => {
    theme.sourceIds.forEach((sourceId) => sourceIds.add(sourceId));
  });
  return [...sourceIds].map((sourceId) => EVIDENCE_SOURCES[sourceId]).filter(Boolean);
}

export function getSourcesByIds(sourceIds = []) {
  return [...new Set(sourceIds)].map((sourceId) => EVIDENCE_SOURCES[sourceId]).filter(Boolean);
}

export function allEvidenceSources() {
  return Object.entries(EVIDENCE_SOURCES).map(([id, source]) => ({ id, ...source }));
}
