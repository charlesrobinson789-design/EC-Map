"""Assemble deploy/docker-compose.yml: one self-contained file (configs inlined) for Hostinger Docker Manager."""
import base64
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))

N8N_IMAGE = "n8nio/n8n:2.42.7"
POSTGRES_IMAGE = "postgres:16-alpine"


def read(path):
    return open(os.path.join(HERE, path), encoding="utf-8").read()


def block(text, indent=6):
    # Compose interpolates $ in config content; escape every literal $.
    pad = " " * indent
    return "\n".join(pad + line if line else "" for line in text.replace("$", "$$").splitlines())


photo = base64.b64encode(open(os.path.join(HERE, "site/charles.jpg"), "rb").read()).decode()
index = read("site/index.html").replace('src="charles.jpg"', f'src="data:image/jpeg;base64,{photo}"')
caddyfile = read("Caddyfile").replace("#ASSESS_BLOCK#", read("assess.caddy") if os.path.exists(os.path.join(HERE, "assess.caddy")) else "")
GLOBAL = "{\n\temail {$ACME_EMAIL}\n}\n"
assert caddyfile.startswith(GLOBAL), "Caddyfile global block changed; update build.py"
# Rehearsal can't answer certificate challenges (the live site holds ports 80/443), so it uses
# Caddy's internal CA instead of asking Let's Encrypt and burning its failure limits.
caddyfile_rehearsal = caddyfile.replace(GLOBAL, "{\n\temail {$ACME_EMAIL}\n\tlocal_certs\n}\n", 1)


def rev(*texts):
    # Compose doesn't recreate a container when only inline config content changes, so each
    # service carries a hash of its configs in its environment: new content -> new container.
    return hashlib.sha256("\0".join(texts).encode()).hexdigest()[:12]


def render(project, ports, live):
    caddy = caddyfile if live else caddyfile_rehearsal
    # Rehearsal writes to its own host folders, never into the live data or backups.
    host = "/opt/ecm" if live else "/opt/ecm/rehearsal"
    caddy_data = """  caddy_data:
    external: true
    name: ${CADDY_DATA_VOLUME:-gratitude-wellness_caddy_data}""" if live else """  # Rehearsal keeps its own certificate store so it never touches the live one.
  caddy_data:"""
    return f"""# GENERATED by consulting/build.py. Edit the sources, then rebuild.
name: {project}

services:
  edge:
    image: caddy:2.11.7-alpine
    restart: unless-stopped
    ports:
{ports}
    environment:
      SITE_DOMAIN: ${{SITE_DOMAIN:-executivecapacitymap.com}}
      ACME_EMAIL: ${{ACME_EMAIL:-charles@executivecapacitymap.com}}
      CONFIG_REV: "{rev(caddy, index)}"
    configs:
      - source: caddyfile
        target: /etc/caddy/Caddyfile
      - source: site_index
        target: /srv/site/index.html
    volumes:
      - caddy_data:/data
      - caddy_config:/config
      - ${{ASSESS_WWW:-/opt/ecm/www}}:/srv/assess:ro
    # The site never waits on the automations stack: if n8n is down, the landing page and intake stay up.
    depends_on:
      - intake

  intake:
    image: python:3.13-alpine
    restart: unless-stopped
    command: ["python", "-u", "/app/intake.py"]
    environment:
      SMTP_HOST: ${{SMTP_HOST:-smtp.hostinger.com}}
      SMTP_PORT: ${{SMTP_PORT:-465}}
      SMTP_USER: ${{SMTP_USER:-charles@executivecapacitymap.com}}
      SMTP_PASSWORD: ${{SMTP_PASSWORD:-}}
      # Production: the mailbox password lives in a root-only file on the server, never in git.
      SMTP_PASSWORD_FILE: /run/secrets/smtp_password
      INTAKE_TO: ${{INTAKE_TO:-charles@executivecapacitymap.com}}
      SMTP_NO_TLS: ${{SMTP_NO_TLS:-0}}
      # Every submission is appended to submissions.jsonl here before the email is attempted.
      DATA_DIR: /data
      # n8n webhook (internal network only); a 404 in the log just means no workflow listens there yet.
      NOTIFY_URL: ${{NOTIFY_URL:-http://n8n:5678/webhook/ecm-intake}}
      CONFIG_REV: "{rev(read("intake.py"))}"
    configs:
      - source: intake_py
        target: /app/intake.py
    volumes:
      - ${{SECRETS_DIR:-/opt/ecm/secrets}}:/run/secrets:ro
      - ${{INTAKE_DATA_DIR:-{host}/data}}:/data

  # One-shot: generates the stack's secrets on first run, prefills the mailbox credentials,
  # and emails Charles his n8n sign-in once (live only). Safe to re-run on every deploy.
  automations-init:
    image: {N8N_IMAGE}
    user: root
    entrypoint: ["node", "/init/init.cjs"]
    restart: "no"
    environment:
      OWNER_EMAIL: ${{OWNER_EMAIL:-charles@executivecapacitymap.com}}
      N8N_URL: https://automations.${{SITE_DOMAIN:-executivecapacitymap.com}}
      WELCOME_EMAIL: "{'1' if live else '0'}"
      CONFIG_REV: "{rev(read("n8n/init.cjs"))}"
    configs:
      - source: automations_init
        target: /init/init.cjs
    volumes:
      - automation_secrets:/secrets
      - ${{SECRETS_DIR:-/opt/ecm/secrets}}:/host-secrets:ro

  postgres:
    image: {POSTGRES_IMAGE}
    restart: unless-stopped
    environment:
      POSTGRES_USER: n8n
      POSTGRES_DB: n8n
      POSTGRES_PASSWORD_FILE: /secrets/pg_password
    volumes:
      - pg_data:/var/lib/postgresql/data
      - automation_secrets:/secrets:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U n8n -d n8n"]
      interval: 5s
      timeout: 5s
      retries: 30
    depends_on:
      automations-init:
        condition: service_completed_successfully

  n8n:
    image: {N8N_IMAGE}
    restart: unless-stopped
    environment:
      DB_TYPE: postgresdb
      DB_POSTGRESDB_HOST: postgres
      DB_POSTGRESDB_DATABASE: n8n
      DB_POSTGRESDB_USER: n8n
      DB_POSTGRESDB_PASSWORD_FILE: /secrets/pg_password
      # Encrypts saved credentials. Lives in the secrets volume, apart from the database dumps.
      N8N_ENCRYPTION_KEY_FILE: /secrets/n8n_encryption_key
      N8N_HOST: automations.${{SITE_DOMAIN:-executivecapacitymap.com}}
      N8N_PROTOCOL: https
      WEBHOOK_URL: https://automations.${{SITE_DOMAIN:-executivecapacitymap.com}}/
      N8N_PROXY_HOPS: 1
      N8N_SECURE_COOKIE: "true"
      GENERIC_TIMEZONE: ${{TIMEZONE:-America/Los_Angeles}}
      TZ: ${{TIMEZONE:-America/Los_Angeles}}
      N8N_DIAGNOSTICS_ENABLED: "false"
      N8N_PERSONALIZATION_ENABLED: "false"
      N8N_ENFORCE_SETTINGS_FILE_PERMISSIONS: "true"
      # Claude connects through the MCP server (OAuth), so the separate REST API stays off.
      N8N_PUBLIC_API_DISABLED: "true"
      N8N_MCP_MANAGED_BY_ENV: "true"
      N8N_MCP_ACCESS_ENABLED: "true"
      # The owner account exists before the first start, so there is never an open setup page.
      N8N_INSTANCE_OWNER_MANAGED_BY_ENV: "true"
      N8N_INSTANCE_OWNER_EMAIL: ${{OWNER_EMAIL:-charles@executivecapacitymap.com}}
      N8N_INSTANCE_OWNER_FIRST_NAME: Charles
      N8N_INSTANCE_OWNER_LAST_NAME: Robinson
      N8N_INSTANCE_OWNER_PASSWORD_HASH_FILE: /secrets/owner_password_hash
      # Mailbox settings for IMAP/SMTP credentials, written by automations-init.
      CREDENTIALS_OVERWRITE_DATA_FILE: /secrets/credentials_overwrite.json
      EXECUTIONS_DATA_PRUNE: "true"
      EXECUTIONS_DATA_MAX_AGE: 336
    volumes:
      - n8n_data:/home/node/.n8n
      - automation_secrets:/secrets:ro
    depends_on:
      postgres:
        condition: service_healthy
      automations-init:
        condition: service_completed_successfully

  # Nightly database dump to /opt/ecm/backups on the server, 14 days kept.
  pg-backup:
    image: {POSTGRES_IMAGE}
    restart: unless-stopped
    command: ["sh", "/backup.sh"]
    environment:
      CONFIG_REV: "{rev(read("n8n/pg-backup.sh"))}"
    configs:
      - source: pg_backup
        target: /backup.sh
    volumes:
      - automation_secrets:/secrets:ro
      - ${{BACKUP_DIR:-{host}/backups}}:/backups
    depends_on:
      postgres:
        condition: service_healthy

configs:
  caddyfile:
    content: |
{block(caddy)}
  site_index:
    content: |
{block(index)}
  intake_py:
    content: |
{block(read("intake.py"))}
  automations_init:
    content: |
{block(read("n8n/init.cjs"))}
  pg_backup:
    content: |
{block(read("n8n/pg-backup.sh"))}

volumes:
  # Reuse the existing Caddy certificate store so the main domain keeps its HTTPS certificate.
{caddy_data}
  caddy_config:
  n8n_data:
  pg_data:
  automation_secrets:
"""


LIVE_PORTS = '      - "80:80"\n      - "443:443"\n      - "443:443/udp"'
# Rehearsal runs beside the live site on host-local ports, to prove startup before any switchover.
REHEARSAL_PORTS = '      - "127.0.0.1:18080:80"\n      - "127.0.0.1:18443:443"'

os.makedirs(os.path.join(HERE, "deploy"), exist_ok=True)
for name, text in (("docker-compose.yml", render("crm-consulting", LIVE_PORTS, True)),
                   ("rehearsal.yml", render("crm-consulting-rehearsal", REHEARSAL_PORTS, False))):
    open(os.path.join(HERE, "deploy", name), "w", encoding="utf-8").write(text)
    print(f"deploy/{name}: {len(text)//1024} KB")
